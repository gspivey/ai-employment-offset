"""Size of the AI cost shock by sigma_ai under the two CES normalizations (referee concern 3).

At the reference point (full diffusion, exposure-1 sector, wage = wage0), reports
the adopter's unit-cost saving 1 - c/w, the reference AI price, and the
single-firm headcount ratio (c/w)**(sigma - theta), using the model's own
functions. Pure evaluation of closed forms; no simulation.

Run from the repo root:
    .venv/bin/python scripts/normalization_cost_saving.py
Writes data/normalization_cost_saving.md.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from model import Parameters  # noqa: E402
from model.firm_dynamics import ces_unit_cost, reference_ai_price  # noqa: E402

OUT = ROOT / "data" / "normalization_cost_saving.md"
SIGMAS = (1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 4.5, 5.0)


def main() -> None:
    L = ["# AI cost shock by sigma_ai under the two CES normalizations", "",
         "Generated by `scripts/normalization_cost_saving.py` with `model.firm_dynamics.ces_unit_cost` and `reference_ai_price`.",
         "Reference point: full diffusion, exposure-1 sector, wage = wage0 = 1, alpha = 0.64 (theta = 2.778).", "",
         "| sigma_ai | none: AI price | none: unit-cost saving | none: headcount ratio | cost_saving: AI price | cost_saving: unit-cost saving | cost_saving: headcount ratio |",
         "|---|---|---|---|---|---|---|"]
    for s in SIGMAS:
        cells = []
        for norm in ("none", "cost_saving"):
            p = Parameters(sigma_ai=s, ces_normalization=norm)
            r = reference_ai_price(p)
            c = float(ces_unit_cost(p.wage0, r, s))
            cells += [f"{r:.3f}", f"{1 - c / p.wage0:.1%}", f"{(c / p.wage0) ** (s - p.theta):.3f}"]
        L.append(f"| {s:g} | " + " | ".join(cells) + " |")
    OUT.write_text("\n".join(L) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
