"""Sensitivity of the headline probabilities to the sigma_ai prior.

The baseline Monte Carlo draws sigma_ai ~ U(2, 5). Because sigma_ai explains
most of the variance, P(offset) partly restates that prior. This script
reweights the existing 2,000 draws (importance weights g(sigma)/u(sigma), so
no re-simulation) to report the headline probabilities under alternative
priors on the same support, and P(offset) conditional on sigma_ai bins.

Outputs
    data/prior_sensitivity.md
    data/prior_sensitivity.csv

Usage
    .venv/bin/python scripts/prior_sensitivity.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "monte_carlo_raw.csv"
OUT_MD = ROOT / "data" / "prior_sensitivity.md"
OUT_CSV = ROOT / "data" / "prior_sensitivity.csv"
ALPHA = 0.64
THETA = 1.0 / (1.0 - ALPHA)

PRIORS = {
    "U(2, 5) (baseline)": lambda s: np.ones_like(s),
    "Triangular, mode 2 (weight on low sigma)": stats.triang(c=0.0, loc=2.0, scale=3.0).pdf,
    "Triangular, mode 5 (weight on high sigma)": stats.triang(c=1.0, loc=2.0, scale=3.0).pdf,
    "U(2.78, 5) (above threshold only)": lambda s: (s >= THETA).astype(float),
    "U(3.5, 5) (high substitution only)": lambda s: (s >= 3.5).astype(float),
}


def main() -> None:
    df = pd.read_csv(RAW)
    sig = df["sigma_ai"].to_numpy()
    off = df["offset"].astype(bool).to_numpy()
    disp = (df["large_firm_employment_effect"] < 0).to_numpy()

    rows = []
    for name, pdf in PRIORS.items():
        w = pdf(sig)
        w = w / w.sum()
        ess = 1.0 / np.sum(w**2)
        rows.append(
            {
                "prior": name,
                "P(offset)": float(np.sum(w * off)),
                "P(large-firm employment falls)": float(np.sum(w * disp)),
                "P(offset given large-firm employment falls)": float(np.sum(w * off * disp) / np.sum(w * disp)),
                "effective sample size": ess,
            }
        )
    tab = pd.DataFrame(rows)
    tab.to_csv(OUT_CSV, index=False)

    bins = []
    for lo in np.arange(2.0, 5.0, 0.5):
        m = (sig >= lo) & (sig < lo + 0.5)
        md = m & disp
        bins.append(
            {
                "sigma_ai": f"[{lo:.1f}, {lo + 0.5:.1f})",
                "P(offset)": off[m].mean(),
                "n": int(m.sum()),
                "P(offset given large-firm employment falls)": off[md].mean() if md.any() else float("nan"),
                "n (falls)": int(md.sum()),
            }
        )
    btab = pd.DataFrame(bins)

    pct = lambda x: f"{x:.1%}"  # noqa: E731
    L = [
        "# Sensitivity to the sigma_ai prior",
        "",
        "Generated by `scripts/prior_sensitivity.py` from `data/monte_carlo_raw.csv` (N = 2,000) by importance",
        "reweighting on sigma_ai. All priors share the baseline support [2, 5]; the other parameters keep their",
        "baseline priors. Effective sample size = 1 / sum(w^2).",
        "",
        "| prior on sigma_ai | P(offset) | P(large-firm empl. falls) | P(offset given falls) | ESS |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        L.append(
            f"| {r['prior']} | {pct(r['P(offset)'])} | {pct(r['P(large-firm employment falls)'])} | "
            f"{pct(r['P(offset given large-firm employment falls)'])} | {r['effective sample size']:.0f} |"
        )
    L += ["", "## P(offset) by sigma_ai bin (prior-free)", "",
          "| sigma_ai | P(offset) | n | P(offset given large-firm empl. falls) | n |", "|---|---|---|---|---|"]
    for b in bins:
        cond = "n/a" if np.isnan(b["P(offset given large-firm employment falls)"]) else pct(b["P(offset given large-firm employment falls)"])
        L.append(f"| {b['sigma_ai']} | {pct(b['P(offset)'])} | {b['n']} | {cond} | {b['n (falls)']} |")
    OUT_MD.write_text("\n".join(L) + "\n")
    print(OUT_MD.read_text())


if __name__ == "__main__":
    main()
