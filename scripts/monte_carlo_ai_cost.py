"""Sensitivity run: the T6 Monte Carlo with the AI price drawn, not fixed.

The baseline (``monte_carlo_t6.py``) holds ``ai_cost_full`` at 1.5, so the AI
price is at or above the wage in every sector, and adoption falls as sigma_ai
rises. That decline is what holds P(offset) near 68% at high sigma_ai. This run
adds the lognormal prior already in ``model.monte_carlo.default_uncertainty()``
(``ai_cost_full ~ lognorm(s=0.4, scale=1.5)``, median 1.5) and keeps the other
four priors unchanged, so the comparison isolates the effect of AI-price
uncertainty.

Outputs
    data/monte_carlo_aicost_raw.csv      one row per replication
    data/monte_carlo_aicost_results.md   headline probabilities vs the baseline

Usage
    .venv/bin/python scripts/monte_carlo_ai_cost.py [--n 2000] [--jobs 6] [--seed 2027]
    .venv/bin/python scripts/monte_carlo_ai_cost.py --analyze-only
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from model import ParameterUncertainty, Parameters  # noqa: E402
import monte_carlo_t6 as t6  # noqa: E402

DATA = ROOT / "data"
RAW_CSV = DATA / "monte_carlo_aicost_raw.csv"
REPORT_MD = DATA / "monte_carlo_aicost_results.md"
AI_COST_PRIOR = stats.lognorm(s=0.4, scale=1.5)


def uncertainty(base: Parameters) -> ParameterUncertainty:
    dists = dict(t6.study_uncertainty(base).distributions)
    dists["ai_cost_full"] = AI_COST_PRIOR
    return ParameterUncertainty(dists)


def simulate(n: int, seed: int, jobs: int) -> pd.DataFrame:
    base = Parameters()
    unc = uncertainty(base)
    param_rng = np.random.default_rng(np.random.SeedSequence(seed).spawn(1)[0])
    sim_seeds = np.random.SeedSequence(seed).generate_state(n, dtype=np.uint32)
    draws = [unc.draw(param_rng) for _ in range(n)]
    df = t6.run(draws, base, sim_seeds, jobs, "aicost")
    df.insert(df.columns.get_loc("entry_cost_post") + 1, "entry_cost_reduction", 1.0 - df["entry_cost_post"] / base.entry_cost_pre)
    df["offset"] = df["net_employment_effect"] > 0
    df["strong_offset"] = df["net_employment_effect"] > t6.STRONG_OFFSET
    df["concentration"] = df["small_firm_employment_effect"] < 0
    return df


def summarize(df: pd.DataFrame, label: str) -> dict:
    disp = df["large_firm_employment_effect"] < 0
    th = 1.0 / (1.0 - Parameters().alpha)

    def p(mask_num, mask_den=None):
        den = mask_den if mask_den is not None else pd.Series(True, index=df.index)
        k, n = int((mask_num & den).sum()), int(den.sum())
        lo, hi = t6.wilson(k, n) if n else (float("nan"), float("nan"))
        return k / n if n else float("nan"), lo, hi, n

    off = df["offset"].astype(bool)
    hi_sig = df["sigma_ai"] >= 3.5
    return {
        "run": label,
        "P(offset)": p(off),
        "P(large firms shrink)": p(disp),
        "P(offset given large firms shrink)": p(off, disp),
        "P(offset given sigma < threshold)": p(off, df["sigma_ai"] < th),
        "P(offset given sigma >= threshold)": p(off, df["sigma_ai"] >= th),
        "P(offset given sigma >= 3.5)": p(off, hi_sig),
        "mean adoption, sigma >= 3.5": (float(df.loc[hi_sig, "adoption_rate"].mean()), None, None, int(hi_sig.sum())),
    }


def sensitivity(df: pd.DataFrame, params: list) -> pd.Series:
    y = df["net_employment_effect"]
    out = {}
    for p_ in params:
        bins = pd.qcut(df[p_], 20, duplicates="drop")
        out[p_] = y.groupby(bins, observed=True).mean().reindex(bins).var(ddof=0) / y.var(ddof=0)
    return pd.Series(out).sort_values(ascending=False)


def report(df: pd.DataFrame, seed: int, runtime: float | None) -> str:
    base = pd.read_csv(t6.RAW_CSV, index_col="replication")
    rows = [summarize(base, "baseline (ai_cost_full = 1.5)"), summarize(df, "ai_cost_full ~ lognorm(0.4, 1.5)")]
    keys = [k for k in rows[0] if k != "run"]
    L = [
        "# Sensitivity: AI price drawn from its prior",
        "",
        f"Generated by `scripts/monte_carlo_ai_cost.py` (seed {seed}, N = {len(df)})."
        + (f" Wall time {runtime / 60:.1f} min." if runtime else ""),
        "Same four priors as `monte_carlo_results.md`, plus `ai_cost_full ~ lognorm(s=0.4, scale=1.5)` (median 1.5),",
        "the prior already in `model.monte_carlo.default_uncertainty()`. The baseline column is recomputed from",
        "`monte_carlo_raw.csv`.",
        "",
        "| quantity | " + " | ".join(r["run"] for r in rows) + " |",
        "|---|" + "---|" * len(rows),
    ]
    for k in keys:
        cells = []
        for r in rows:
            v, lo, hi, n = r[k]
            cells.append(f"{v:.1%} (n = {n})" if lo is None else f"{v:.1%} [{lo:.1%}, {hi:.1%}] (n = {n})")
        L.append(f"| {k} | " + " | ".join(cells) + " |")
    L += ["", "## P(offset) by sigma_ai bin", "", "| sigma_ai | baseline | AI price drawn |", "|---|---|---|"]
    for lo in np.arange(2.0, 5.0, 0.5):
        cells = []
        for d in (base, df):
            m = (d["sigma_ai"] >= lo) & (d["sigma_ai"] < lo + 0.5)
            cells.append(f"{d.loc[m, 'offset'].astype(bool).mean():.1%} (n = {int(m.sum())})")
        L.append(f"| [{lo:.1f}, {lo + 0.5:.1f}) | " + " | ".join(cells) + " |")
    s1 = sensitivity(df, t6.PARAMS + ["ai_cost_full"])
    L += ["", "## First-order sensitivity of net_employment_effect (20 quantile bins, not bias-adjusted)", "",
          "| parameter | S1 |", "|---|---|"]
    L += [f"| {k} | {v:.3f} |" for k, v in s1.items()]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n", type=int, default=2000)
    ap.add_argument("--jobs", type=int, default=6)
    ap.add_argument("--seed", type=int, default=2027)
    ap.add_argument("--analyze-only", action="store_true")
    args = ap.parse_args()
    runtime = None
    if args.analyze_only:
        df = pd.read_csv(RAW_CSV, index_col="replication")
    else:
        t0 = time.time()
        df = simulate(args.n, args.seed, args.jobs)
        runtime = time.time() - t0
        df.to_csv(RAW_CSV)
        print(f"wrote {RAW_CSV} ({len(df)} rows); {runtime:.0f}s", flush=True)
    REPORT_MD.write_text(report(df, args.seed, runtime))
    print(f"wrote {REPORT_MD}")


if __name__ == "__main__":
    main()
