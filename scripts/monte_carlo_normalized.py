"""The T6 Monte Carlo under the normalized CES (referee concern 3).

Same four priors and seed as ``monte_carlo_t6.py``; the only change is
``ces_normalization = "cost_saving"``, which holds the adopter's reference
unit-cost saving fixed while sigma_ai varies. Comparing the variance
decomposition with the original run shows how much of sigma_ai's apparent
importance came from sigma_ai also scaling the size of the AI shock.

Reported as shares of draws and variance shares. These are summaries of an
assumed prior, not probabilities about the world.

Outputs
    data/monte_carlo_normalized_raw.csv
    data/monte_carlo_normalized_results.md

Usage
    .venv/bin/python scripts/monte_carlo_normalized.py [--n 2000] [--jobs 6] [--seed 2026]
    .venv/bin/python scripts/monte_carlo_normalized.py --analyze-only
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from model import Parameters  # noqa: E402
import monte_carlo_t6 as t6  # noqa: E402

RAW = ROOT / "data" / "monte_carlo_normalized_raw.csv"
REPORT = ROOT / "data" / "monte_carlo_normalized_results.md"


def simulate(n: int, seed: int, jobs: int) -> pd.DataFrame:
    base = Parameters(ces_normalization="cost_saving")
    unc = t6.study_uncertainty(base)
    param_rng = np.random.default_rng(np.random.SeedSequence(seed).spawn(1)[0])
    sim_seeds = np.random.SeedSequence(seed).generate_state(n, dtype=np.uint32)
    draws = [unc.draw(param_rng) for _ in range(n)]
    df = t6.run(draws, base, sim_seeds, jobs, "normalized")
    df.insert(df.columns.get_loc("entry_cost_post") + 1, "entry_cost_reduction", 1.0 - df["entry_cost_post"] / base.entry_cost_pre)
    df["offset"] = df["net_employment_effect"] > 0
    return df


def s1(df: pd.DataFrame, y: str = "net_employment_effect") -> pd.Series:
    out = {}
    for p in t6.PARAMS:
        bins = pd.qcut(df[p], 20, duplicates="drop")
        out[p] = df[y].groupby(bins, observed=True).mean().reindex(bins).var(ddof=0) / df[y].var(ddof=0)
    return pd.Series(out)


def report(df: pd.DataFrame, seed: int, runtime: float | None) -> str:
    base = pd.read_csv(t6.RAW_CSV, index_col="replication")
    theta = Parameters().theta
    L = ["# Monte Carlo under the normalized CES", "",
         f"Generated by `scripts/monte_carlo_normalized.py` (seed {seed}, N = {len(df)})."
         + (f" Wall time {runtime / 60:.1f} min." if runtime else ""),
         "Same priors and seed as `monte_carlo_results.md`; `ces_normalization = cost_saving` (reference unit-cost saving 11.65%).",
         "Shares of draws summarize an assumed prior. They are not probabilities about the world.", "",
         "## First-order variance shares of the net labor-demand effect (20 quantile bins)", "",
         "| parameter | original (AI price fixed) | normalized (cost saving fixed) |", "|---|---|---|"]
    a, b = s1(base), s1(df)
    for p in t6.PARAMS:
        L.append(f"| {t6.PARAM_LABELS[p]} | {a[p]:.3f} | {b[p]:.3f} |")
    L += ["", "## Mean net labor-demand effect and share of draws with a positive effect, by sigma_ai", "",
          "| sigma_ai | original mean | original share > 0 | normalized mean | normalized share > 0 |", "|---|---|---|---|---|"]
    for lo in np.arange(2.0, 5.0, 0.5):
        cells = []
        for d in (base, df):
            m = (d.sigma_ai >= lo) & (d.sigma_ai < lo + 0.5)
            cells += [f"{d.loc[m, 'net_employment_effect'].mean():+.1%}", f"{(d.loc[m, 'net_employment_effect'] > 0).mean():.0%}"]
        L.append(f"| [{lo:.1f}, {lo + 0.5:.1f}) | " + " | ".join(cells) + " |")
    for name, d in (("original", base), ("normalized", df)):
        disp = d.large_firm_employment_effect < 0
        L += ["", f"- {name}: mean adoption {d.adoption_rate.mean():.1%}; large-firm employment falls in {disp.mean():.0%} of draws; "
              f"share of draws above theta = {theta:.2f} with large-firm decline {(disp & (d.sigma_ai > theta)).sum() / (d.sigma_ai > theta).sum():.0%}."]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=2000)
    ap.add_argument("--jobs", type=int, default=6)
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--analyze-only", action="store_true")
    a = ap.parse_args()
    runtime = None
    if a.analyze_only:
        df = pd.read_csv(RAW, index_col="replication")
    else:
        t0 = time.time()
        df = simulate(a.n, a.seed, a.jobs)
        runtime = time.time() - t0
        df.to_csv(RAW)
    REPORT.write_text(report(df, a.seed, runtime))
    print(REPORT.read_text())


if __name__ == "__main__":
    main()
