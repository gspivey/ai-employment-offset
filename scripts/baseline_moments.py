"""Model-versus-data moments of the baseline (pre-AI) economy.

Runs the default ``Parameters()`` economy with AI switched off for 5 seeds
(burn-in, then ``n_periods`` recorded periods), computes
``model.calibration.simulated_moments`` over all recorded periods, and adds
the Hill estimate of the Pareto tail exponent for firms with 100+ employees
from the final cross-section. Data targets: 2019 values from
``data/cloud_era_baseline.md`` (Census BDS, 2023 release) where available, and
otherwise the unverified placeholders in ``model/calibration.py``.

The defaults are NOT calibrated: this script only reports how far the
baseline is from the data. No parameter is fitted.

Run from the repo root:
    .venv/bin/python scripts/baseline_moments.py
Writes data/baseline_moments.md.
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from model import Parameters, initialize_economy, run_simulation  # noqa: E402
from model.calibration import BASELINE_TARGETS, simulated_moments  # noqa: E402

SEEDS = (11, 12, 13, 14, 15)
OUT = ROOT / "data" / "baseline_moments.md"

# (moment key, label, data value or None, data source)
DATA = [
    ("entry_rate", "Entry (startup) rate", 0.085,
     "BDS 2019 startup rate, `data/cloud_era_baseline.md` table 2.1"),
    ("exit_rate", "Exit rate", None,
     "no repo source; `model/calibration.py` placeholder 0.08 (unverified)"),
    ("emp_share_large", "Employment share of firms with 500+ employees", 0.530,
     "BDS 2019, `data/cloud_era_baseline.md` table 3.4"),
    ("firm_share_small", "Share of firms with fewer than 20 employees", 0.879,
     "BDS 2019, `data/cloud_era_baseline.md` table 3.1"),
    ("mean_firm_size", "Mean firm size (employees)", 24.7,
     "BDS 2019, `data/cloud_era_baseline.md` table 3.2"),
    ("size_tail_exponent", "Pareto tail exponent, firms with 100+ employees", None,
     "no source for the 100+ cutoff; `model/calibration.py` cites Axtell (2001), 1.06, fitted to the whole distribution"),
]


def main() -> None:
    p = Parameters()
    t0 = time.time()
    rows, extra = [], []
    for s in SEEDS:
        econ = initialize_economy(p, seed=s)
        h = run_simulation(p, seed=s, ai_enabled=False, economy=econ)
        m = simulated_moments(h, p, economy=econ)
        rows.append(m)
        extra.append({
            "firms": float(h["n_firms"].mean()),
            "employment": float(h["aggregate_employment"].mean()),
            "firms_5000_plus": int((econ.size >= 5000).sum()),
            "firms_500_plus": int((econ.size >= 500).sum()),
        })
    df, ex = pd.DataFrame(rows, index=SEEDS), pd.DataFrame(extra, index=SEEDS)
    placeholder = {t.name: t.value for t in BASELINE_TARGETS}

    def fmt(key, v):
        if key in ("mean_firm_size", "size_tail_exponent"):
            return f"{v:.2f}"
        return f"{v:.1%}"

    L = ["# Baseline (pre-AI) moments: model versus data", "",
         f"Generated by `scripts/baseline_moments.py`: default `Parameters()`, AI off, seeds {list(SEEDS)}, "
         f"burn-in {p.burn_in} periods, then {p.n_periods} recorded periods (moments averaged over them; tail exponent from the final "
         f"cross-section, Hill estimator, firms with 100+ employees). Wall time {time.time() - t0:.0f}s.",
         "The model is not calibrated; nothing here was fitted. `model/calibration.py` marks every placeholder target `verified=False`.", "",
         "| moment | model mean | model s.d. across seeds | data | data source | calibration.py placeholder |",
         "|---|---|---|---|---|---|"]
    for key, label, val, src in DATA:
        L.append(f"| {label} | {fmt(key, df[key].mean())} | {fmt(key, df[key].std(ddof=1))} | "
                 f"{fmt(key, val) if val is not None else 'not sourced'} | {src} | "
                 f"{fmt(key, placeholder[key]) if key in placeholder else '-'} |")
    L += ["", "## Scale of the model economy", "",
          f"- Mean number of firms: {ex.firms.mean():,.0f}; mean employment: {ex.employment.mean():,.0f} workers.",
          f"- Firms with 500+ employees in the final cross-section: {ex.firms_500_plus.mean():.1f} on average "
          f"(range {ex.firms_500_plus.min()}-{ex.firms_500_plus.max()}); with 5,000+: {ex.firms_5000_plus.mean():.1f} "
          f"(range {ex.firms_5000_plus.min()}-{ex.firms_5000_plus.max()}).",
          "", "## Per-seed values", "",
          "| seed | " + " | ".join(df.columns) + " |", "|---" * (len(df.columns) + 1) + "|"]
    L += [f"| {s} | " + " | ".join(f"{v:.4f}" for v in r) + " |" for s, r in df.iterrows()]
    OUT.write_text("\n".join(L) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
