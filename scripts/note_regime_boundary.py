"""Figures and numbers for the short model note (note/note.tex).

Everything here is analytic (Propositions 2 and 3 of the note), evaluated at
illustrative parameter values; nothing is estimated.

Prop. 2 (industry offset condition, fixed wage). With adopter employment share
a, entrant employment share e, adopter unit-cost ratio k = c/w < 1 and scale
elasticity theta, labor demand changes by
    dN/N = a (k^(sigma - theta) - 1) + e (G_E - 1),
    G_E  = kappa^(-eta) * exp(theta * Delta) * S(Delta, kappa) * ell,
where S is the change in the selection term [1 - Phi(v)], v = u - theta*s,
u = (ln z_e - mu)/s. Entry offsets displacement iff dN >= 0. The minimal
entrant productivity shift Delta*(sigma) solves dN = 0.

Prop. 3 (entrant quality vs entry cost). Elasticities of entrant employment:
    E_q = theta + lambda(v)/s            (per log point of entrant quality)
    E_c = eta + lambda(v) * w_c/(theta s) (per log point of entry-cost cut)
with lambda the inverse Mills ratio and w_c = c_e/(c_e + F).

Outputs
    paper/figures/note_boundary.{pdf,png}
    data/note_numbers.md

Usage
    .venv/bin/python scripts/note_regime_boundary.py
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy import optimize, stats  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "paper" / "figures" / "note_boundary"
NUM = ROOT / "data" / "note_numbers.md"

# Illustrative values (model defaults where they exist)
S_ENT = 0.60          # sd of entrant log productivity (entrant_prod_sd)
P_ENTER = 0.70        # share of potential entrants clearing the cutoff pre-AI
ETA = 0.30            # founder-pool elasticity (entry_pool_elasticity)
KAPPA = 0.85          # entry cost multiplier (15% cut)
K = 1 - 0.1165        # adopter unit-cost ratio (normalized cost saving)
W_C = 1.0             # entry cost share of (entry cost + PV of fixed costs); 1 = upper bound


def mills(v):
    return stats.norm.pdf(v) / stats.norm.sf(v)


def entry_factor(delta, theta, kappa=KAPPA, eta=ETA, s=S_ENT, p_enter=P_ENTER, w_c=W_C, ell=1.0):
    """G_E: ratio of entrant-cohort labor demand after vs before the shock."""
    u0 = stats.norm.isf(p_enter)  # standardized cutoff, pre-shock
    v0 = u0 - theta * s
    # cutoff moves with ln z_e = (1/theta) ln(c_e + F) => du = w_c ln(kappa)/(theta s); mean shift: du = -delta/s
    u1 = u0 + w_c * np.log(kappa) / (theta * s) - delta / s
    v1 = u1 - theta * s
    sel = stats.norm.sf(v1) / stats.norm.sf(v0)
    return kappa ** (-eta) * np.exp(theta * delta) * sel * ell


def dN(sigma, delta, theta, a_over_e, k=K, **kw):
    """Labor-demand change per unit of entrant employment share: (dN/N)/e."""
    return a_over_e * (k ** (sigma - theta) - 1.0) + (entry_factor(delta, theta, **kw) - 1.0)


def delta_star(sigma, theta, a_over_e, **kw):
    f = lambda d: dN(sigma, d, theta, a_over_e, **kw)  # noqa: E731
    if f(-0.5) >= 0:
        return -0.5
    return optimize.brentq(f, -0.5, 3.0)


def main() -> None:
    sig = np.linspace(1.05, 9.0, 300)
    fig, axes = plt.subplots(1, 3, figsize=(11.5, 3.9), dpi=150, sharey=True)
    for ax, theta, lab in zip(axes, (1 / (1 - 0.64), 1 / (1 - 0.75), 1 / (1 - 0.85)),
                              (r"$\alpha=0.64$", r"$\alpha=0.75$", r"$\alpha=0.85$")):
        for ae, ls in ((1.0, ":"), (3.0, "--"), (10.0, "-")):
            ds = [delta_star(s, theta, ae) for s in sig]
            ax.plot(sig, ds, ls=ls, color="#1d3557", lw=1.8, label=f"a/e = {ae:g}")
        ax.axvline(theta, color="#e76f51", lw=1)
        ax.text(theta + 0.1, 0.42, rf"$\theta={theta:.2f}$", color="#e76f51", fontsize=9)
        ax.axhline(0, color="#999999", lw=0.8)
        ax.set_ylim(-0.05, 0.5)
        ax.set_xlim(1, 9)
        ax.set_title(lab + r"  ($\theta = 1/(1-\alpha)$)", fontsize=10)
        ax.set_xlabel(r"Labor-AI elasticity $\sigma$", fontsize=9)
        ax.fill_between(sig, -0.05, 0.5, where=sig <= theta, color="#2a9d8f", alpha=0.08)
    axes[0].set_ylabel(r"Entrant quality shift needed, $\Delta^*$ (log points)", fontsize=9)
    axes[2].legend(fontsize=8, frameon=False, loc="upper left")
    fig.tight_layout()
    FIG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG.with_suffix(".pdf"))
    fig.savefig(FIG.with_suffix(".png"))

    theta = 1 / (1 - 0.64)
    u0 = stats.norm.isf(P_ENTER)
    v0 = u0 - theta * S_ENT
    lam = mills(v0)
    Eq = theta + lam / S_ENT
    Ec = ETA + lam * W_C / (theta * S_ENT)
    q_effect = entry_factor(0.10, theta, kappa=1.0) - 1
    c_effect = entry_factor(0.0, theta, kappa=0.8) - 1
    lines = [
        "# Numbers for the short model note", "",
        "Generated by `scripts/note_regime_boundary.py`. Illustrative values: "
        f"s = {S_ENT}, pre-AI entry share = {P_ENTER}, eta = {ETA}, kappa = {KAPPA}, k = {K:.4f}, w_c = {W_C}.", "",
        f"- theta (alpha = 0.64) = {theta:.3f}; standardized cutoff u0 = {u0:.3f}; v0 = u0 - theta*s = {v0:.3f}; lambda(v0) = {lam:.4f}",
        f"- Elasticity of entrant labor demand w.r.t. entrant quality: E_q = {Eq:.3f}",
        f"- Elasticity w.r.t. entry cost (cut): E_c = {Ec:.3f}; ratio E_q/E_c = {Eq / Ec:.1f}",
        f"- Exact effect of Delta = 0.10: {q_effect:+.1%}; of a 20% entry-cost cut (kappa = 0.8): {c_effect:+.1%}",
        f"- Reversal requires eta > theta + (lambda/s)(1 - w_c/theta) = {theta + lam / S_ENT * (1 - W_C / theta):.2f}",
        "",
        "## Delta* (log points) needed for offset, alpha = 0.64",
        "", "| sigma | a/e = 1 | a/e = 3 | a/e = 10 |", "|---|---|---|---|",
    ]
    for s in (2.0, 2.78, 3.0, 3.5, 4.0, 5.0, 8.0):
        lines.append(f"| {s:g} | " + " | ".join(f"{delta_star(s, theta, ae):.3f}" for ae in (1, 3, 10)) + " |")
    lim = {ae: (np.log(1 + ae) + ETA * np.log(KAPPA)) / theta for ae in (1, 3, 10)}
    lines += ["", "Limit as sigma -> infinity, ignoring selection: Delta* -> [ln(1 + a/e) + eta ln kappa]/theta = "
              + ", ".join(f"{v:.3f} (a/e={ae})" for ae, v in lim.items())]
    NUM.write_text("\n".join(lines) + "\n")
    print(NUM.read_text())


if __name__ == "__main__":
    main()
