"""Every BFS number quoted in the revised paper that is not read directly off a
``scripts/bfs_causal_analysis.py`` output, recomputed from the raw file.

Data: Census BFS ``data/bfs_raw/bfs_monthly.csv`` (November 12, 2026 vintage,
through October 2026). Growth rates and shares use unadjusted counts (``sa=U``)
summed over the stated months, matching the earlier drafts; gaps and
permutation ranks use the seasonally adjusted series (``sa=A``) and exactly the
annual outcome of ``bfs_causal_analysis.py`` (log of the mean monthly SA count,
2026 = all available months, i.e. January--October).

Run from the repo root:
    .venv/bin/python scripts/bfs_revision_numbers.py
Writes data/bfs_revision_numbers.md.
"""
from __future__ import annotations

import itertools
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import bfs_causal_analysis as bca  # noqa: E402

RAW = ROOT / "data" / "bfs_raw" / "bfs_monthly.csv"
OUT = ROOT / "data" / "bfs_revision_numbers.md"
M = bca.MONTHS
BASE = bca.BASE_YEAR


def raw() -> pd.DataFrame:
    d = pd.read_csv(RAW, dtype=str)
    d = d[d.geo == "US"].copy()
    d["year"] = d.year.astype(int)
    for m in M:
        d[m] = pd.to_numeric(d[m], errors="coerce")
    return d


def total(d, series, sector, year, months, sa="U") -> float:
    r = d[(d.sa == sa) & (d.series == series) & (d.naics_sector == sector) & (d.year == year)]
    assert len(r) == 1, (series, sector, year)
    v = r[months].iloc[0]
    assert v.notna().all(), (series, sector, year, months)
    return float(v.sum())


def growth(d, series, sector, y1, y0, months) -> float:
    return total(d, series, sector, y1, months) / total(d, series, sector, y0, months) - 1


def gap_table(wide: pd.DataFrame, groups) -> pd.DataFrame:
    """Gap of each group's mean log level vs the mean of all other sectors, relative to BASE."""
    g = pd.DataFrame({"+".join(p): wide.loc[list(p)].mean() - wide.drop(index=list(p)).mean() for p in groups}).T
    return g.sub(g[BASE], axis=0)


def rank(gaps: pd.DataFrame, key: str, year: int) -> tuple[int, int, float]:
    obs = gaps.loc[key, year]
    r = int((gaps[year] >= obs - 1e-12).sum())
    return r, len(gaps), r / len(gaps)


def main() -> None:
    d = raw()
    L = ["# BFS numbers for the revised paper", "",
         "Generated by `scripts/bfs_revision_numbers.py` from `data/bfs_raw/bfs_monthly.csv` "
         "(November 12, 2026 vintage, data through October 2026).",
         "Growth rates and shares: unadjusted counts summed over the stated months. "
         "Gaps and ranks: seasonally adjusted, same annual outcome as `scripts/bfs_causal_analysis.py`.", ""]

    jo, js = M[:10], M[:9]
    L += ["## Levels and growth (unadjusted, summed)", ""]
    rows = [
        ("Applications, Jan-Oct 2026 vs Jan-Oct 2025", growth(d, "BA_BA", "TOTAL", 2026, 2025, jo)),
        ("Planned-wage applications (WBA), Jan-Oct 2026 vs 2025", growth(d, "BA_WBA", "TOTAL", 2026, 2025, jo)),
        ("High-propensity applications (HBA), Jan-Oct 2026 vs 2025", growth(d, "BA_HBA", "TOTAL", 2026, 2025, jo)),
        ("Information (51) applications, Jan-Oct 2026 vs 2025", growth(d, "BA_BA", "NAICS51", 2026, 2025, jo)),
        ("Professional (54) applications, Jan-Oct 2026 vs 2025", growth(d, "BA_BA", "NAICS54", 2026, 2025, jo)),
        ("Finance (52) applications, Jan-Oct 2026 vs 2025", growth(d, "BA_BA", "NAICS52", 2026, 2025, jo)),
        ("Applications, Jan-Sep 2026 vs Jan-Sep 2025 (revised)", growth(d, "BA_BA", "TOTAL", 2026, 2025, js)),
        ("WBA, Jan-Sep 2026 vs Jan-Sep 2025 (revised)", growth(d, "BA_WBA", "TOTAL", 2026, 2025, js)),
        ("Applications, 2019 vs 2006 (full years)", growth(d, "BA_BA", "TOTAL", 2019, 2006, M)),
        ("WBA, 2019 vs 2006 (full years)", growth(d, "BA_WBA", "TOTAL", 2019, 2006, M)),
        ("Applications, 2025 vs 2019 (full years)", growth(d, "BA_BA", "TOTAL", 2025, 2019, M)),
    ]
    L += ["| quantity | value |", "|---|---|"] + [f"| {k} | {v:+.1%} |" for k, v in rows]
    shares = [
        ("WBA share of applications, Jan-Oct 2026, all sectors",
         total(d, "BA_WBA", "TOTAL", 2026, jo) / total(d, "BA_BA", "TOTAL", 2026, jo)),
        ("WBA share of applications, Jan-Oct 2026, Information",
         total(d, "BA_WBA", "NAICS51", 2026, jo) / total(d, "BA_BA", "NAICS51", 2026, jo)),
        ("WBA share of applications, 2019, all sectors",
         total(d, "BA_WBA", "TOTAL", 2019, M) / total(d, "BA_BA", "TOTAL", 2019, M)),
        ("WBA share of applications, 2019, Information",
         total(d, "BA_WBA", "NAICS51", 2019, M) / total(d, "BA_BA", "NAICS51", 2019, M)),
    ]
    L += [f"| {k} | {v:.1%} |" for k, v in shares]
    wba = {s: growth(d, "BA_WBA", s, 2026, 2025, jo) for s in bca.LABELS}
    neg = sum(v < 0 for v in wba.values())
    L += ["", f"- WBA, Jan-Oct 2026 vs 2025, by sector: falls in {neg} of {len(wba)} sectors; range "
          f"{min(wba.values()):+.1%} ({bca.LABELS[min(wba, key=wba.get)]}) to {max(wba.values()):+.1%} ({bca.LABELS[max(wba, key=wba.get)]}); "
          f"Information {wba['NAICS51']:+.1%}."]

    # ---- SA annual panel, identical to bfs_causal_analysis.load -------------------------
    panel = bca.load(RAW, "BA_BA")
    wide = panel.pivot(index="sector", columns="year", values="y")
    sectors = list(wide.index)
    pairs = list(itertools.combinations(sectors, 2))
    gp = gap_table(wide, pairs)
    key = "NAICS51+NAICS54"
    L += ["", "## Permutation ranks of the 2026 gap (all applications, SA)", ""]
    r, n, p = rank(gp, key, 2026)
    L.append(f"- 51+54, 2026 gap {gp.loc[key, 2026]:.3f}; rank {r} of {n} pairs; one-sided p = {p:.3f}.")
    r20, _, p20 = rank(gp, key, 2020)
    L.append(f"- 51+54, 2020 gap {gp.loc[key, 2020]:.3f}; rank {r20} of {n} (one-sided p = {p20:.3f}).")
    pre_ranks = {y: rank(gp, key, y)[0] for y in range(2015, 2022)}
    L.append(f"- 51+54, best (smallest) rank in 2015-2021: {min(pre_ranks.values())} (year {min(pre_ranks, key=pre_ranks.get)}).")
    above = gp[2026][gp[2026] > gp.loc[key, 2026] + 1e-12].sort_values(ascending=False)
    with55 = [k for k in above.index if "NAICS55" in k]
    L.append(f"- Pairs with a larger 2026 gap than 51+54: {len(above)}; of these, {len(with55)} include Management of companies (55): "
             + ", ".join(f"{k} ({v:.3f})" for k, v in above.items()) + ".")
    pairs55 = [k for k in gp.index if "NAICS55" in k]
    L.append(f"- Pairs that include 55: {len(pairs55)}; of these, {int((gp.loc[pairs55, 2026] > 0).sum())} have a positive 2026 gap and "
             f"{int((gp.loc[pairs55, 2026] >= gp.loc[key, 2026] - 1e-12).sum())} rank at or above 51+54.")
    # Drop 55 from the universe entirely
    w55 = wide.drop(index="NAICS55")
    gp_no55 = gap_table(w55, list(itertools.combinations(w55.index, 2)))
    r2, n2, p2 = rank(gp_no55, key, 2026)
    L.append(f"- Dropping 55 from the sample: 51+54 2026 gap {gp_no55.loc[key, 2026]:.3f}; rank {r2} of {n2}; one-sided p = {p2:.3f}.")
    pre_no55 = {y: rank(gp_no55, key, y)[0] for y in range(2015, 2022)}
    L.append(f"- Dropping 55: best rank of 51+54 in 2015-2021: {min(pre_no55.values())} of {n2}.")

    # ---- Adding Finance (52) ---------------------------------------------------------
    L += ["", "## Adding Finance (52) to the exposed group", ""]
    triples = list(itertools.combinations(sectors, 3))
    gt = gap_table(wide, triples)
    tkey = "NAICS51+NAICS52+NAICS54"
    rt, nt, pt = rank(gt, tkey, 2026)
    L.append(f"- 51+52+54 (vs all other 16 sectors): 2026 gap {gt.loc[tkey, 2026]:.3f}; rank {rt} of {nt} sector triples; one-sided p = {pt:.3f}.")
    L.append(f"- Ratio to the 51+54 gap: {gt.loc[tkey, 2026] / gp.loc[key, 2026]:.2f}.")
    # Regression version, same design as the headline event study (controls exclude 23, 44-45)
    df3 = bca.sample(panel, ["NAICS51", "NAICS52", "NAICS54"], bca.PLACEBO)
    es3 = bca.event_study(df3).set_index("year")
    df2 = bca.sample(panel, bca.TREATED, bca.PLACEBO)
    es2 = bca.event_study(df2).set_index("year")
    L.append(f"- Event-study coefficient 2026, 51+54 vs 15 controls: {es2.loc[2026, 'coef']:.3f} (s.e. {es2.loc[2026, 'se']:.3f}); "
             f"51+52+54 vs 14 controls: {es3.loc[2026, 'coef']:.3f} (s.e. {es3.loc[2026, 'se']:.3f}); ratio {es3.loc[2026, 'coef'] / es2.loc[2026, 'coef']:.2f}.")
    sl3, sl3_se = bca.pre_slope(df3)
    d3t = df3[df3.year <= 2019]
    f3, f3_se = bca.did(d3t, list(range(2010, 2016)), list(range(2016, 2020)))
    L.append(f"- 51+52+54 vs 14 controls: pre-trend 2010-2022 {sl3:+.4f}/yr (s.e. {sl3_se:.4f}); fake 2016 shock {f3:.3f} (s.e. {f3_se:.3f}).")
    df52 = bca.sample(panel, ["NAICS52"], bca.PLACEBO + bca.TREATED)
    es52 = bca.event_study(df52).set_index("year")
    ctrl14 = [s for s in sectors if s not in ["NAICS23", "NAICSRET", "NAICS51", "NAICS52", "NAICS54"]]
    simple52 = (wide.loc["NAICS52"] - wide.loc[ctrl14].mean())
    simple52 = simple52 - simple52[BASE]
    L.append(f"- Finance (52) alone, 2026 vs 2022, against the 14 controls excluding 23, 44-45, 51, 52, 54: simple gap {simple52[2026]:.3f}; "
             f"event-study coefficient {es52.loc[2026, 'coef']:.3f} (s.e. {es52.loc[2026, 'se']:.3f}).")
    # Same months (Jan-Oct) in every year, so 2026 and 2022 cover the same calendar window
    wjo = bca.load(RAW, "BA_BA", M[:10]).pivot(index="sector", columns="year", values="y")
    s52 = wjo.loc["NAICS52"] - wjo.loc[ctrl14].mean()
    L.append(f"- Same comparison on Jan-Oct months in every year: simple gap {s52[2026] - s52[BASE]:.3f}.")
    gjo = gap_table(wjo, [("NAICS51", "NAICS54"), ("NAICS51", "NAICS52", "NAICS54")])
    L.append(f"- Jan-Oct months in every year, vs all other sectors: 51+54 {gjo.loc[key, 2026]:.3f}; 51+52+54 {gjo.loc[tkey, 2026]:.3f}.")

    # ---- Equal vs application weighting ------------------------------------------------
    L += ["", "## Equal versus application weighting (SA, annual mean monthly level)", ""]
    lvl = panel.pivot(index="sector", columns="year", values="level")
    ctrl15 = [s for s in sectors if s not in bca.TREATED + bca.PLACEBO]
    eq = wide.loc[bca.TREATED].mean() - wide.loc[ctrl15].mean()
    wt = np.log(lvl.loc[bca.TREATED].sum()) - np.log(lvl.loc[ctrl15].sum())
    eq, wt = eq - eq[BASE], wt - wt[BASE]
    share54 = float(lvl.loc["NAICS54", BASE] / lvl.loc[bca.TREATED, BASE].sum())
    L.append(f"- 2026 gap vs the 15 controls, equal-weighted mean of logs: {eq[2026]:.3f}; log of summed applications (application-weighted): {wt[2026]:.3f}.")
    L.append(f"- 2025: equal {eq[2025]:.3f}, weighted {wt[2025]:.3f}. Professional services (54) is {share54:.0%} of 51+54 applications in 2022.")

    # ---- Placebos and the 2020 jump ----------------------------------------------------
    es = pd.read_csv(ROOT / "data" / "bfs_event_study.csv")
    def c(design, year, series="BA_BA"):
        r = es[(es.design == design) & (es.year == year) & (es.series == series)].iloc[0]
        return f"{r.coef:.3f} (s.e. {r.se:.3f})"
    L += ["", "## Read from data/bfs_event_study.csv (for convenience)", ""]
    for des in ["AI-exposed (51+54)", "Information (51)", "Professional (54)", "Placebo: Construction (23)", "Placebo: Retail (44-45)"]:
        L.append(f"- {des}: 2020 {c(des, 2020)}; 2025 {c(des, 2025)}; 2026 {c(des, 2026)}.")
    L.append(f"- High-propensity, 51+54: 2026 {c('AI-exposed (51+54)', 2026, 'BA_HBA')}; Information alone 2026 {c('Information (51)', 2026, 'BA_HBA')}.")
    pre = es[(es.design == "AI-exposed (51+54)") & (es.series == "BA_BA") & es.year.between(2015, 2021)]
    L.append(f"- 51+54 event coefficients 2015-2021 range from {pre.coef.min():.3f} to {pre.coef.max():.3f}.")

    # ---- Monthly gap ------------------------------------------------------------------
    mg = pd.read_csv(ROOT / "data" / "bfs_monthly_gap.csv", index_col=0, parse_dates=True)["AI-exposed (51+54)"]
    post = mg[mg.index >= "2023-01-01"]
    stays = next(t for t in post.index if (post[post.index >= t] > 0.05).all())
    L += ["", "## Monthly gap (data/bfs_monthly_gap.csv, 51+54 vs the other 15 sectors, 2022 mean = 0)", ""]
    L.append(f"- First month from which the gap stays above 0.05 log points: {stays:%B %Y} ({mg[stays]:.3f}).")
    L.append(f"- September 2026: {mg['2026-09-01']:.3f}; October 2026: {mg['2026-10-01']:.3f} "
             f"(exp - 1 = {np.exp(mg['2026-10-01']) - 1:+.0%}).")
    L.append(f"- Largest monthly gap in 2019-2022: {mg[mg.index < '2023-01-01'].max():.3f} ({mg[mg.index < '2023-01-01'].idxmax():%B %Y}).")

    OUT.write_text("\n".join(L) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
